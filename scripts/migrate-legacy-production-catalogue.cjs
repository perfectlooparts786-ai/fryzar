"use strict";

/**
 * Repeatable, lossless migration generator for FRYZAR's legacy production D1
 * (`fryzar-production`) catalogue into the v9 schema (`0009_platform_completion.sql`).
 *
 * SAFETY POLICY:
 * - This script NEVER connects to or modifies remote production D1.
 * - It transforms an exported JSON snapshot of legacy `categories` and `products`
 *   into deterministic RFC-4122 v4-compatible UUIDs, preserving 100% of slugs,
 *   SKUs, bilingual names/descriptions, integer paisa prices, availability flags,
 *   and tracked stock units, plus opening `inventory_adjustments`,
 *   `inventory_movements`, and `audit_logs`.
 */

const crypto = require("node:crypto");
const fs = require("node:fs");

function deterministicUuid(namespaceKey) {
  const hash = crypto.createHash("sha256").update("fryzar-legacy-v1:" + namespaceKey).digest("hex");
  return [
    hash.slice(0, 8),
    hash.slice(8, 12),
    "4" + hash.slice(13, 16),
    "8" + hash.slice(17, 20),
    hash.slice(20, 32)
  ].join("-");
}

function sqlLiteral(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isSafeInteger(value)) throw new Error("Non-integer numeric value in legacy migration: " + value);
    return String(value);
  }
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function generateCatalogueMigrationSql(snapshot) {
  if (!snapshot || !Array.isArray(snapshot.categories) || !Array.isArray(snapshot.products)) {
    throw new Error("Invalid legacy snapshot: expected { categories: [], products: [] }.");
  }

  const categoryIdMap = new Map();
  const lines = [
    "-- Generated by scripts/migrate-legacy-production-catalogue.cjs",
    "-- Target schema: 0009_platform_completion.sql",
    ""
  ];

  let totalStockUnits = 0;

  for (const cat of snapshot.categories) {
    const legacyId = String(cat.id);
    const newId = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(legacyId)
      ? legacyId.toLowerCase()
      : deterministicUuid("category:" + legacyId);
    categoryIdMap.set(legacyId, newId);

    const slug = String(cat.slug).trim().toLowerCase();
    const nameEn = String(cat.name_en || "").trim();
    const nameUr = String(cat.name_ur || nameEn).trim();
    const descEn = String(cat.description_en || "").trim();
    const descUr = String(cat.description_ur || "").trim();
    const sortOrder = Number.isSafeInteger(Number(cat.sort_order)) ? Number(cat.sort_order) : 0;
    const rawActive = cat.is_active !== undefined ? cat.is_active : cat.active;
    const isActive = rawActive === 0 || rawActive === false ? 0 : 1;

    lines.push(
      `INSERT INTO categories (id, slug, name_ur, name_en, description_ur, description_en, sort_order, is_active)` +
      ` VALUES (${sqlLiteral(newId)}, ${sqlLiteral(slug)}, ${sqlLiteral(nameUr)}, ${sqlLiteral(nameEn)}, ${sqlLiteral(descUr)}, ${sqlLiteral(descEn)}, ${sqlLiteral(sortOrder)}, ${sqlLiteral(isActive)})` +
      ` ON CONFLICT(slug) DO UPDATE SET name_ur=excluded.name_ur, name_en=excluded.name_en, description_ur=excluded.description_ur, description_en=excluded.description_en, sort_order=excluded.sort_order, is_active=excluded.is_active, updated_at=CURRENT_TIMESTAMP;`
    );
  }

  lines.push("");

  for (const prod of snapshot.products) {
    const legacyId = String(prod.id);
    const newId = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(legacyId)
      ? legacyId.toLowerCase()
      : deterministicUuid("product:" + legacyId);

    const mappedCatId = prod.category_id ? (categoryIdMap.get(String(prod.category_id)) || null) : null;
    const slug = String(prod.slug).trim().toLowerCase();
    const sku = prod.sku ? String(prod.sku).trim() : ("LEGACY-" + slug.toUpperCase().replace(/[^A-Z0-9]+/g, "-").slice(0, 32));
    const nameEn = String(prod.name_en || "").trim();
    const nameUr = String(prod.name_ur || nameEn).trim();
    const descEn = String(prod.description_en || "").trim();
    const descUr = String(prod.description_ur || "").trim();
    const pricePaisa = Number(prod.price_paisa);
    if (!Number.isSafeInteger(pricePaisa) || pricePaisa < 0) {
      throw new Error(`Invalid price_paisa for product ${legacyId}: ${prod.price_paisa}`);
    }
    const compareAtPaisa = prod.compare_at_paisa === null || prod.compare_at_paisa === undefined
      ? null
      : Number(prod.compare_at_paisa);
    if (compareAtPaisa !== null && (!Number.isSafeInteger(compareAtPaisa) || compareAtPaisa < 0)) {
      throw new Error(`Invalid compare_at_paisa for product ${legacyId}: ${prod.compare_at_paisa}`);
    }
    const stockQty = prod.stock_qty === null || prod.stock_qty === undefined ? null : Number(prod.stock_qty);
    if (stockQty !== null) {
      if (!Number.isSafeInteger(stockQty) || stockQty < 0) {
        throw new Error(`Invalid stock_qty for product ${legacyId}: ${prod.stock_qty}`);
      }
      totalStockUnits += stockQty;
    }
    const isAvailable = prod.is_available === 0 || prod.is_available === false ? 0 : 1;
    const isFeatured = prod.is_featured === 1 || prod.is_featured === true || prod.featured === 1 || prod.featured === true ? 1 : 0;
    const sortOrder = Number.isSafeInteger(Number(prod.sort_order)) ? Number(prod.sort_order) : 0;
    const imageUrl = prod.image_url && /^https:\/\//i.test(String(prod.image_url)) ? String(prod.image_url) : null;

    const adjId = deterministicUuid("legacy-opening-adjustment:" + legacyId);
    const auditId = deterministicUuid("legacy-migration-audit:" + legacyId);
    const metadataJson = JSON.stringify({
      legacy_id: legacyId,
      legacy_category_id: prod.category_id || null,
      migrated_price_paisa: pricePaisa,
      migrated_stock_qty: stockQty,
      migrated_is_featured: Boolean(isFeatured)
    });

    lines.push(
      `INSERT INTO products (id, category_id, sku, slug, name_ur, name_en, description_ur, description_en, price_paisa, compare_at_paisa, image_url, stock_qty, is_available, is_archived, is_featured, sort_order)` +
      ` VALUES (${sqlLiteral(newId)}, ${sqlLiteral(mappedCatId)}, ${sqlLiteral(sku)}, ${sqlLiteral(slug)}, ${sqlLiteral(nameUr)}, ${sqlLiteral(nameEn)}, ${sqlLiteral(descUr)}, ${sqlLiteral(descEn)}, ${sqlLiteral(pricePaisa)}, ${sqlLiteral(compareAtPaisa)}, ${sqlLiteral(imageUrl)}, ${sqlLiteral(stockQty)}, ${sqlLiteral(isAvailable)}, 0, ${sqlLiteral(isFeatured)}, ${sqlLiteral(sortOrder)})` +
      ` ON CONFLICT(slug) DO UPDATE SET category_id=excluded.category_id, name_ur=excluded.name_ur, name_en=excluded.name_en, description_ur=excluded.description_ur, description_en=excluded.description_en, price_paisa=excluded.price_paisa, compare_at_paisa=excluded.compare_at_paisa, is_available=excluded.is_available, is_featured=excluded.is_featured, sort_order=excluded.sort_order, updated_at=CURRENT_TIMESTAMP;`
    );

    if (stockQty !== null && stockQty > 0) {
      lines.push(
        `INSERT OR IGNORE INTO inventory_adjustments (id, product_id, actor_staff_id, reason, delta_qty, previous_stock_qty, new_stock_qty, note)` +
        ` SELECT ${sqlLiteral(adjId)}, id, NULL, 'stock_received', ${sqlLiteral(stockQty)}, 0, ${sqlLiteral(stockQty)}, 'Migrated opening stock from fryzar-production (${legacyId})'` +
        ` FROM products WHERE slug = ${sqlLiteral(slug)};`
      );
      lines.push(
        `INSERT OR IGNORE INTO inventory_movements (id, product_id, delta_qty, reason, reference_type, reference_id, note)` +
        ` SELECT ${sqlLiteral(adjId)}, id, ${sqlLiteral(stockQty)}, 'stock_received', 'legacy_migration', ${sqlLiteral(adjId)}, 'Migrated opening stock from fryzar-production (${legacyId})'` +
        ` FROM products WHERE slug = ${sqlLiteral(slug)};`
      );
    }

    lines.push(
      `INSERT OR IGNORE INTO audit_logs (id, actor_role, action, entity_type, entity_id, metadata_json)` +
      ` SELECT ${sqlLiteral(auditId)}, 'system', 'legacy.product_migrated', 'product', id, ${sqlLiteral(metadataJson)}` +
      ` FROM products WHERE slug = ${sqlLiteral(slug)};`
    );
  }

  return {
    sql: lines.join("\n") + "\n",
    summary: {
      categories_migrated: snapshot.categories.length,
      products_migrated: snapshot.products.length,
      total_stock_units: totalStockUnits,
      category_id_map: Object.fromEntries(categoryIdMap)
    }
  };
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const inputIdx = args.indexOf("--input");
  const outputIdx = args.indexOf("--output");
  if (inputIdx < 0 || !args[inputIdx + 1]) {
    process.stderr.write("Usage: node scripts/migrate-legacy-production-catalogue.cjs --input <snapshot.json> [--output <migration.sql>]\n");
    process.exit(1);
  }
  const raw = JSON.parse(fs.readFileSync(args[inputIdx + 1], "utf8"));
  const result = generateCatalogueMigrationSql(raw);
  if (outputIdx >= 0 && args[outputIdx + 1]) {
    fs.writeFileSync(args[outputIdx + 1], result.sql, "utf8");
  } else {
    process.stdout.write(result.sql);
  }
  process.stderr.write("Migration SQL generated: " + JSON.stringify(result.summary) + "\n");
}

module.exports = { deterministicUuid, generateCatalogueMigrationSql };
